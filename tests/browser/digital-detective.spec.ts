  const database = new Database(String(testInfo.config.metadata.detectiveDatabase));
  const salt = Buffer.alloc(16,7), password = "browser-test-password-2026", encoded = `scrypt$16384$8$1$${salt.toString("hex")}$${scryptSync(password,salt,64).toString("hex")}`;
  database.prepare("INSERT OR IGNORE INTO admin_users(username,password_hash,role) VALUES ('browser-admin',?,'super_admin')").run(encoded);
  database.prepare("INSERT OR IGNORE INTO admin_users(username,password_hash,role) VALUES ('browser-display',?,'display_operator')").run(encoded);
  await page.goto("/staff"); await page.getByLabel("USERNAME",{ exact:true }).fill("browser-admin"); await page.getByLabel("PASSWORD",{ exact:true }).fill(password); await page.getByRole("button",{ name:"SIGN IN",exact:false }).click();
  await expect(page.getByRole("heading",{ name:"Digital Detective",exact:true })).toBeVisible();
  await page.locator(".dd-admin").getByRole("button",{ name:"CASES",exact:true }).click();
  await page.getByRole("button",{ name:/The Midnight Breach · v1/ }).click();
  await expect(page.getByLabel("Case JSON editor")).toContainText("The Midnight Breach");
  const adminCases = await (await page.request.get("/api/detective/admin/cases")).json();
  const c = adminCases[0];
  expect((await page.request.put(`/api/detective/admin/cases/${c.id}`,{ data:{ content:c.content,status:"published" } })).status()).toBe(200);
  const comp = { title:"Browser Event",status:"open",caseId:c.id,version:2,difficulty:"beginner",seed:"fair-test-seed",startAt:Date.now()-1000,endAt:Date.now()+600000,participation:"both",revealAfterClose:true };
