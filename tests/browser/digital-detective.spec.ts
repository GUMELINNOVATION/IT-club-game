  const active: Attempt = await (await page.request.get(`/api/detective/attempts/${a.id}`)).json();
  for (const f of Object.keys(report.answers)) if (!active.case.options[f].includes(report.answers[f])) report.answers[f] = active.case.options[f].find(o => !["ops.maintenance","lab-check","No account involved"].includes(o))!;
  const submission = await page.request.post(`/api/detective/attempts/${a.id}/submit`,{ data:report });
