  expect(a.difficulty).toBe("beginner"); expect(a.version).toBe(2);
  await page.request.post(`/api/detective/attempts/${a.id}/begin`);
  // Test-owned rubric conversion verifies every public randomized identifier.
  const rubric = c.content.solution;
  const report = { answers:rubric.answers,citations:Object.fromEntries(Object.entries(rubric.evidence as Record<string,string[]>).map(([f,ids]) => [f,ids.map(id => `ev-${hash(`fair-test-seed:${c.id}:${id}`).slice(0,12)}`)])),reasoning:Object.fromEntries(Object.keys(rubric.answers).map(f => [f,"Records correlate identity, object and timestamps directly."])),timeline:rubric.timeline.map((id: string) => `event-${hash(`fair-test-seed:${c.id}:${id}`).slice(0,12)}`) };
